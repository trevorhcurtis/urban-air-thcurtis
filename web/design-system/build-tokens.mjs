// Writes app/tokens.generated.css from the token files. Run with `pnpm run tokens`.
// The output is committed. A test fails if it drifts from the token source.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { loadTokens } from "./resolve.mjs";

const here = dirname(fileURLToPath(import.meta.url));
export const OUTPUT = join(here, "..", "app", "tokens.generated.css");
export const RESOLVED_OUTPUT = join(here, "tokens.resolved.json");

const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/** Turns a token path into a Tailwind theme variable name, dropping the leading group segment. */
// Token groups whose Tailwind theme namespace differs from the group name.
const NAMESPACES = {
  fontSize: "text",
  gridColumns: "grid-template-columns",
};

function themeName(path) {
  const [group, ...rest] = path.split(".");
  return `--${NAMESPACES[group] ?? group}-${rest.map(kebab).join("-")}`;
}

export function buildCss(tokens = loadTokens()) {
  const lines = [];
  lines.push("/* Generated by design-system/build-tokens.mjs from design-system/tokens. Do not edit by hand. */");
  lines.push("");
  lines.push("/*");
  lines.push(" * Tailwind theme. Defaults for colors, font sizes, radii, and shadows are cleared, so only");
  lines.push(" * design tokens produce utilities. Any other class renders nothing and fails the token tests.");
  lines.push(" */");
  lines.push("@theme {");
  for (const ns of ["--color", "--text", "--radius", "--shadow"]) {
    lines.push(`  ${ns}-*: initial;`);
  }

  for (const path of Object.keys(tokens.semantic)) {
    lines.push(`  ${themeName(path)}: ${tokens.resolved[path].value};`);
  }
  for (const path of Object.keys(tokens.theme)) {
    const name = themeName(path);
    const value = tokens.resolved[path].value;
    if (path.startsWith("font.")) {
      lines.push(`  ${name}: ${value};`);
    } else if (path.startsWith("fontSize.")) {
      lines.push(`  ${name}: ${value};`);
      lines.push(`  ${name}--line-height: ${tokens.resolved[path].lineHeight};`);
    } else if (path.startsWith("control.")) {
      const suffix = path.slice("control.".length).split(".").map(kebab).join("-");
      lines.push(`  --height-control-${suffix}: ${value};`);
      lines.push(`  --min-height-control-${suffix}: ${value};`);
    } else {
      lines.push(`  ${name}: ${value};`);
    }
  }
  // Tailwind's default body font comes from --default-font-family. Point it at the UI token, and clear the
  // built-in font-sans utility so only font-ui (and font-brand) exist.
  lines.push("  --font-sans: initial;");
  lines.push("  --default-font-family: var(--font-ui);");
  lines.push("}");
  lines.push("");

  lines.push(":root {");
  for (const path of Object.keys(tokens.primitives)) {
    lines.push(`  --primitive-${path.split(".").slice(1).map(kebab).join("-")}: ${tokens.primitives[path].value};`);
  }
  lines.push("}");
  lines.push("");
  return lines.join("\n");
}

/** Resolved semantic colors for the styleguide and tests. Same values as the CSS, in a form the app can import. */
export function buildResolvedJson(tokens = loadTokens()) {
  const colors = Object.keys(tokens.semantic).map((path) => {
    const [, ...rest] = path.split(".");
    return { name: rest.map(kebab).join("-"), group: rest[0], token: path, value: tokens.resolved[path].value };
  });
  return `${JSON.stringify({ colors }, null, 2)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const tokens = loadTokens();
  const css = buildCss(tokens);
  writeFileSync(OUTPUT, css);
  writeFileSync(RESOLVED_OUTPUT, buildResolvedJson(tokens));
  console.log(`Wrote ${OUTPUT} (${css.split("\n").length} lines) and ${RESOLVED_OUTPUT}`);
}
